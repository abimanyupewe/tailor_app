import 'package:flutter/material.dart';

class SliderData {
  final String id;
  final String imageUrl;
  final String link;
  final String textAction;
  final Color color;
  final String title;
  final String description;

  SliderData({
    required this.id,
    required this.imageUrl,
    required this.link,
    required this.textAction,
    required this.color,
    required this.title,
    required this.description,
  });
}